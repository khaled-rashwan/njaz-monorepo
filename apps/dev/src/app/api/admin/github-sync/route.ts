import { NextResponse } from 'next/server';
import { executeGraphQL, QUERIES, MUTATIONS } from '@/lib/amplify-server';

function getAuthToken(request: Request): string | null {
    const auth = request.headers.get('Authorization');
    if (!auth) return null;
    return auth.startsWith('Bearer ') ? auth.slice(7) : auth;
}

// Ensure the token exists
const GITHUB_TOKEN = process.env.GITHUB_TOKEN;

/**
 * Helper to call GitHub REST API
 */
async function githubRequest(endpoint: string, method: string = 'GET', body: any = null) {
    if (!GITHUB_TOKEN) throw new Error('GITHUB_TOKEN rests in the .env file but is missing.');

    const res = await fetch(`https://api.github.com${endpoint}`, {
        method,
        headers: {
            'Authorization': `token ${GITHUB_TOKEN}`,
            'Accept': 'application/vnd.github.v3+json',
            'Content-Type': 'application/json',
        },
        body: body ? JSON.stringify(body) : undefined,
    });

    if (!res.ok) {
        let errMessage = 'GitHub API Error';
        try {
            const errData = await res.json();
            errMessage = errData.message || errMessage;
        } catch (e) {}
        throw new Error(`${errMessage} (Status: ${res.status})`);
    }

    return res.json();
}

export async function POST(request: Request) {
    const token = getAuthToken(request);
    if (!token) return NextResponse.json({ error: 'Authentication required' }, { status: 401 });
    if (!GITHUB_TOKEN) return NextResponse.json({ error: 'GitHub Integration not configured.' }, { status: 500 });

    try {
        const body = await request.json();
        const { inquiryId, githubRepo } = body;

        if (!inquiryId || !githubRepo) {
            return NextResponse.json({ error: 'inquiryId and githubRepo are required' }, { status: 400 });
        }

        // 1. Fetch tasks for this inquiry
        const tasksResult = await executeGraphQL<{
            listDevTasks: { items: any[] };
        }>(QUERIES.listDevTasks, { limit: 100 }, token);

        let tasks = (tasksResult.listDevTasks?.items || []).filter((t: any) => t.inquiryId === inquiryId);

        if (tasks.length === 0) {
            return NextResponse.json({ message: 'No tasks to sync.' });
        }

        // 2. Fetch inquiry details
        const inquiryResult = await executeGraphQL<{
            getDevInquiry: any;
        }>(QUERIES.getDevInquiry, { id: inquiryId }, token);
        const inquiry = inquiryResult.getDevInquiry;

        if (!inquiry) {
            return NextResponse.json({ error: 'Inquiry not found' }, { status: 404 });
        }

        const syncedTaskIds: string[] = [];

        // 3. Create GitHub issues for tasks that don't have one
        for (const task of tasks) {
            if (task.githubIssueNumber) continue; // Already synced

            const issueBody = `**Phase:** ${task.phase || 'N/A'}
**Type:** ${task.type || 'N/A'}
**Estimated Hours:** ${task.estimatedHours || 'N/A'}

${task.description || ''}

_Autogenerated from Njaz Dev Platform_`;

            try {
                // Determine labels based on task type
                const labels = ['njaz-dev'];
                if (task.type) labels.push(task.type);

                // Create Issue
                const issue = await githubRequest(`/repos/${githubRepo}/issues`, 'POST', {
                    title: `[${task.phase || 'Task'}] ${task.title}`,
                    body: issueBody,
                    labels: labels
                });

                // Update DynamoDB task with GitHub URL & Number
                await executeGraphQL(MUTATIONS.updateDevTask, {
                    input: {
                        id: task.id,
                        githubIssueNumber: issue.number,
                        githubIssueUrl: issue.html_url,
                    }
                }, token);
                
                syncedTaskIds.push(task.id);
            } catch (issueErr: any) {
                console.error(`Failed to sync task ${task.id} to GitHub:`, issueErr.message);
                // Continue with other tasks even if one fails
            }
        }

        return NextResponse.json({ 
            success: true, 
            syncedCount: syncedTaskIds.length,
            message: `Successfully synced ${syncedTaskIds.length} tasks to ${githubRepo}`
        });

    } catch (error: any) {
        console.error('❌ GitHub Sync Error:', error);
        return NextResponse.json(
            { error: 'GitHub Sync Failed', message: error.message },
            { status: 500 },
        );
    }
}
